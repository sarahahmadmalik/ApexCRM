// Regenerates PART 2 of supabase/seed.sql from supabase/data/firms-import.json (the PDF firm list).
// Part 1 (your admin login) is kept exactly as it is in the file.
//
//   node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { completedCitiesSql, resolveCompleted } from "./lib/completed-sql.mjs";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const seedPath = join(root, "supabase", "seed.sql");
const firms = JSON.parse(readFileSync(join(root, "supabase", "data", "firms-import.json"), "utf8"));

const NL = "\n";
const lit = (v) => (v === null || v === undefined || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);

const original = readFileSync(seedPath, "utf8").replace(/\r\n/g, NL);
const marker = original.search(/-- =+\n-- PART 2/);
const part1 = (marker === -1 ? original : original.slice(0, marker)).trimEnd() + NL + NL;

const batches = [];
for (let i = 0; i < firms.length; i += 100) {
  const rows = firms.slice(i, i + 100).map((f) => {
    const at = `${f.sent_on ?? "2026-09-14"}T09:00:00Z`;
    return `  (${[f.name, f.country, f.state, f.city, f.status, f.website, f.contact_email, f.notes, at].map(lit).join(", ")})`;
  });
  batches.push(
    [
      "insert into firms (name, country, state, city, status, website, contact_email, notes, created_at, updated_at)",
      "select v.name, v.country, v.state, v.city, v.status::firm_status, v.website, v.contact_email, v.notes, v.at::timestamptz, v.at::timestamptz",
      "from (values",
      rows.join("," + NL),
      ") as v (name, country, state, city, status, website, contact_email, notes, at)",
      "where not exists (select 1 from firms f where f.name = v.name and f.city = v.city and f.contact_email is not distinct from v.contact_email);",
    ].join(NL)
  );
}

const completedList = JSON.parse(readFileSync(join(root, "supabase", "data", "completed-cities.json"), "utf8"));
const completed = resolveCompleted(completedList, firms);
if (completed.unknown.length) console.warn("WARNING: not found among the imported firms:", JSON.stringify(completed.unknown));
const days = [...new Set(firms.map((f) => f.sent_on).filter(Boolean))].sort();
const bySource = firms.reduce((a, f) => ((a[f.source] = (a[f.source] ?? 0) + 1), a), {});
const countries = [...new Set(firms.map((f) => f.country))].sort();
const part2 = `-- ============================================================================
-- PART 2 — real outreach data (${firms.length} firms in ${countries.length} countries: ${countries.join(", ")})
-- Sources (PDFs in the project root):
--   "Dua Dev UG-FirmContactList_DE_11092026.pdf"    lead-tracking register, ${bySource.register ?? 0} firms, emails ${days[0]} to 14.09.2026
--   "Dua Dev UG-FirmContactList_DE_11092026_1.pdf"  contact list, ${bySource.list ?? 0} firms, emails 14.09.2026 to ${days[days.length - 1]}
-- Generated by scripts/build-seed.mjs from supabase/data/firms-import.json — regenerate, don't edit.
--
-- Safe to run more than once: a firm is only inserted if none with the same name, city and email exists.
-- Each firm is dated by the day its email was sent, so the dashboard timeline and recent activity are real.
-- ============================================================================

${batches.join(NL + NL)}

-- The insert trigger logged every firm's first status as "now"; move it to the day the email went out.
update firm_status_history h
set changed_at = f.created_at
from firms f
where h.firm_id = f.id and h.old_status is null and h.changed_at > f.created_at;

-- Daily dashboard history from those send dates (cumulative), so trends work from day one.
insert into dashboard_daily_snapshot (
  snapshot_date, total_firms, sent_count, responded_count, negotiation_count, client_count,
  in_progress_count, cities_completed, cities_total
)
select
  d::date,
  count(f.id),
  count(f.id),                                   -- a reply's date isn't recorded, so replies count as "sent" in the past
  0, 0, 0, 0, 0,
  count(distinct (f.country, f.state, f.city))
from generate_series((select min(created_at)::date from firms), current_date - 1, interval '1 day') as d
left join firms f on f.created_at::date <= d::date
group by d
on conflict (snapshot_date) do nothing;

-- Today's row, from the live data.
select record_dashboard_snapshot();

-- ============================================================================
-- PART 3 — cities marked COMPLETED (by hand, from supabase/data/completed-cities.json)
-- "In progress" needs no entry: a city becomes in progress automatically once one of its firms has been emailed.
-- ============================================================================

${completedCitiesSql(completed.rows)}`;

writeFileSync(seedPath, (part1 + part2).replace(/\n/g, "\r\n"));
console.log(`supabase/seed.sql: kept Part 1, wrote Part 2 with ${firms.length} firms in ${batches.length} batches, Part 3 with ${completed.rows.length} completed cities.`);
